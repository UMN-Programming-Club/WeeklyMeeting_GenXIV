#include <bits/stdc++.h>
using namespace std;

int main() {

    /* BASIC ARITHMETIC OPERATIONS */
    int a = 10, b = 5;
    cout << "Penjumlahan: " << a + b << '\n';
    cout << "Pengurangan: " << a - b << '\n';
    cout << "Perkalian: " << a * b << '\n';
    cout << "Pembagian: " << a / b << '\n';
    cout << "Modulus: " << a % b << '\n';

    /* BASIC BITWISE OPERATIONS */
    a = 3, b = 6;
    cout << "AND: " << (a & b) << '\n';
    cout << "OR: " << (a | b) << '\n';
    cout << "XOR: " << (a ^ b) << '\n';
    cout << "Left Shift: " << (a << b) << '\n';
    cout << "Right Shift: " << (a >> b) << '\n';

    return 0;
}
