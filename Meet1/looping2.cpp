#include <bits/stdc++.h>
using namespace std;

int main() {

    /* WHILE LOOP */
    int i = 0; // Deklarasi Variabel
    while (i < 10) // Kondisi
    {
        /*
         * Kode di dalam while
        */

        cout << i << '\n';

        i++; // Cara Increment / Decrement
    }

    return 0;
}
