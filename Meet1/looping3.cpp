#include <bits/stdc++.h>
using namespace std;

int main() {

    /* DO WHILE LOOP */
    int i = 0; // Deklarasi Variabel
    do
    {
        /*
         * Kode di dalam do while
        */
        cout << i << '\n';

        i++; // Cara Increment / Decrement
    } while (i < 10);

    return 0;
}
