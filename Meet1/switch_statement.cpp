#include <bits/stdc++.h>
using namespace std;

int main() {

    /* SWITCH STATEMENT */
    int nilai = 1;
    switch (nilai)
    {
        case 0:
            cout << "Angka 0!\n";
            break;
        case 1:
            cout << "Angka 1!\n";
            break;
        default:
            cout << "Angka lain!\n";
            break;
    }

    return 0;
}





